#!/usr/bin/env bash
# Assemble the static site that Vercel serves.
#
# TADASHI's voice engine also runs entirely in the browser, so the app works as
# a static site: no server, no API keys. Only Server mode (which streams PCM to
# the Python DSP) needs a backend and is disabled in this build.
#
# Output:
#   public/index.html
#   public/static/styles.css
#   public/static/js/{app,worklet,analysis,offline}.js
#   public/static/voices.json        <- the voice bank, used instead of /api/voices
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/public"

rm -rf "$OUT"
mkdir -p "$OUT/static/js"

cp "$ROOT/app/static/index.html" "$OUT/index.html"
cp "$ROOT/app/static/styles.css" "$OUT/static/styles.css"
cp "$ROOT/app/static/js/"*.js "$OUT/static/js/"
# `app/static/voices.json` is the voice bank in the same shape /api/voices
# returns, so the page can load it directly when there is no backend. It is
# generated by scripts/export_voices.py; tests/test_api.py fails if it drifts.
cp "$ROOT/app/static/voices.json" "$OUT/static/voices.json"

echo "static build written to $OUT"
find "$OUT" -type f | sed "s#$ROOT/##" | sort
